import pathlib
p = pathlib.Path('make_figures_torch.py')
t = p.read_text(encoding='utf-8')
t = t.replace('"font.size": 9,', '"font.size": 11,')
t = t.replace('"axes.titlesize": 10,', '"axes.titlesize": 13,')
t = t.replace('"axes.labelsize": 9,', '"axes.labelsize": 11,')
t = t.replace('"legend.fontsize": 7,', '"legend.fontsize": 9,')
t = t.replace('"xtick.labelsize": 8,', '"xtick.labelsize": 10,')
t = t.replace('"ytick.labelsize": 8,', '"ytick.labelsize": 10,')
t = t.replace('fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))', 'fig, axes = plt.subplots(1, 2, figsize=(15, 6.5))')
t = t.replace('fontsize=7\n    )', 'fontsize=9\n    )')
t = t.replace('fontsize=7)\n    axes[0]', 'fontsize=9)\n    axes[0]')
t = t.replace('fontsize=7)\n    axes[1]', 'fontsize=9)\n    axes[1]')
p.write_text(t, encoding='utf-8')
print('figures patched')
